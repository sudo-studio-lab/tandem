/**
 * `tandem` command for agent hooks (research S4). Writes %LOCALAPPDATA%\Tandem\bin\tandem.cmd
 * and an extensionless `tandem` sh script that run the app's exe in node mode on the CLI bundle,
 * then adds that folder to the user's PATH. No electron import: usable from a plain node script.
 */
import { execFile } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

export const SHIM_MARKER = "tandem-desktop-shim";

export interface ShimOptions {
  /** The app executable (process.execPath). */
  exe: string;
  cliPath: string;
  gitExe: string;
  binDir: string;
  log: (msg: string) => void;
}

const NON_ASCII = /[^\x00-\x7f]/;

function cmdQuote(s: string): string {
  // Batch: % must be doubled; " cannot occur in Windows paths. ! is harmless (no delayed expansion).
  return s.replace(/%/g, "%%");
}

export function renderCmd(o: Pick<ShimOptions, "exe" | "cliPath" | "gitExe">): string {
  const needsUtf8 = [o.exe, o.cliPath, o.gitExe].some((p) => NON_ASCII.test(p));
  const lines = ["@echo off", `rem ${SHIM_MARKER} (generated by Tandem; rewritten on every start)`, "setlocal"];
  if (needsUtf8) {
    // File is UTF-8: switch the console to code page 65001 while cmd reads our paths, restore after.
    lines.push(
      "set \"TANDEM_CP=\"",
      "for /f \"tokens=* delims=\" %%a in ('chcp') do for %%b in (%%a) do set \"TANDEM_CP=%%b\"",
      "chcp 65001 >nul",
    );
  }
  lines.push(
    "set \"ELECTRON_RUN_AS_NODE=1\"",
    `set "TANDEM_GIT=${cmdQuote(o.gitExe)}"`,
    `"${cmdQuote(o.exe)}" "${cmdQuote(o.cliPath)}" %*`,
    "set \"TANDEM_RC=%ERRORLEVEL%\"",
  );
  if (needsUtf8) lines.push("if defined TANDEM_CP chcp %TANDEM_CP% >nul");
  lines.push("exit /b %TANDEM_RC%", "");
  return lines.join("\r\n");
}

function shQuote(s: string): string {
  return `'${s.replace(/\\/g, "/").replace(/'/g, `'\\''`)}'`;
}

export function renderSh(o: Pick<ShimOptions, "exe" | "cliPath" | "gitExe">): string {
  return [
    "#!/bin/sh",
    `# ${SHIM_MARKER} (generated by Tandem; rewritten on every start)`,
    "export ELECTRON_RUN_AS_NODE=1",
    `export TANDEM_GIT=${shQuote(o.gitExe)}`,
    `exec ${shQuote(o.exe)} ${shQuote(o.cliPath)} "$@"`,
    "",
  ].join("\n");
}

function writeIfOurs(file: string, content: string, log: (m: string) => void): void {
  if (existsSync(file)) {
    const head = readFileSync(file, "utf8").split(/\r?\n/, 6).join("\n");
    if (!head.includes(SHIM_MARKER)) {
      log(`shim: ${file} exists and is not ours; leaving it alone`);
      return;
    }
    if (readFileSync(file, "utf8") === content) return;
  }
  writeFileSync(file, content, "utf8");
}

const PS_SCRIPT = `
$ErrorActionPreference = 'Stop'
$dir = $env:TANDEM_SHIM_DIR
$key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)
if ($null -eq $key) { throw 'cannot open HKCU\\Environment' }
$raw = $key.GetValue('Path', $null, [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
$kind = [Microsoft.Win32.RegistryValueKind]::ExpandString
if ($null -ne $raw) { $kind = $key.GetValueKind('Path') } else { $raw = '' }
if ($kind -ne [Microsoft.Win32.RegistryValueKind]::String -and $kind -ne [Microsoft.Win32.RegistryValueKind]::ExpandString) { throw "unexpected Path kind $kind" }
function Norm([string]$p) { [Environment]::ExpandEnvironmentVariables($p.Trim().Trim('"')).TrimEnd('\\').ToLowerInvariant() }
$want = Norm $dir
$has = $false
foreach ($e in ($raw -split ';')) { if ($e.Trim() -ne '' -and (Norm $e) -eq $want) { $has = $true } }
if ($has) { Write-Output 'present'; exit 0 }
$new = if ($raw.Trim() -eq '') { $dir } else { $raw.TrimEnd(';') + ';' + $dir }
$key.SetValue('Path', $new, $kind)
$key.Close()
Add-Type -Namespace Win32 -Name Native -MemberDefinition '[System.Runtime.InteropServices.DllImport("user32.dll", CharSet=System.Runtime.InteropServices.CharSet.Auto, SetLastError=true)] public static extern System.IntPtr SendMessageTimeout(System.IntPtr hWnd, uint Msg, System.UIntPtr wParam, string lParam, uint fuFlags, uint uTimeout, out System.UIntPtr lpdwResult);'
$r = [UIntPtr]::Zero
[void][Win32.Native]::SendMessageTimeout([IntPtr]0xFFFF, 0x1A, [UIntPtr]::Zero, 'Environment', 2, 5000, [ref]$r)
Write-Output 'added'
`;

export type PathResult = "added" | "present" | "failed";

export function ensureOnUserPath(binDir: string, log: (m: string) => void): Promise<PathResult> {
  const encoded = Buffer.from(PS_SCRIPT, "utf16le").toString("base64");
  return new Promise((resolve) => {
    execFile(
      "powershell.exe",
      ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-EncodedCommand", encoded],
      { env: { ...process.env, TANDEM_SHIM_DIR: binDir }, windowsHide: true, timeout: 20_000 },
      (err, stdout, stderr) => {
        if (err) {
          log(`shim: PATH update failed: ${err.message} ${stderr}`.trim());
          return resolve("failed");
        }
        const out = stdout.trim();
        resolve(out === "added" ? "added" : out === "present" ? "present" : "failed");
      },
    );
  });
}

export function defaultBinDir(): string {
  const base = process.env.LOCALAPPDATA ?? path.join(process.env.USERPROFILE ?? "", "AppData", "Local");
  return path.join(base, "Tandem", "bin");
}

/** Write both shim files, then make sure the folder is on the user PATH. */
export async function ensureShim(o: ShimOptions): Promise<PathResult> {
  mkdirSync(o.binDir, { recursive: true });
  writeIfOurs(path.join(o.binDir, "tandem.cmd"), renderCmd(o), o.log);
  writeIfOurs(path.join(o.binDir, "tandem"), renderSh(o), o.log);
  return ensureOnUserPath(o.binDir, o.log);
}
